"""Real EZKL proof fixture for contracts/test/VolMarket.t.sol.

Reuses out/fixed/{model.compiled,pk.key,vk.key,settings.json} and out/kzg15.srs: only witness,
prove and verify run here, never setup/calibrate/compile. Intermediates go to out/fixture/.

Features follow VolMarket.createRound: 17 segment means b_j = floorDiv(C_{j+1} - C_j, delta),
f_j = b_{j+1} - b_j, x_int_j = clamp(f_j, -64, 64) * 128, model input x = x_int / 4096.

Usage (each step is its own process so `/usr/bin/time -l` reports per-step peak memory):
  uv run python prove_fixture.py <input|witness|prove|verify|export|all>
"""
import asyncio
import inspect
import json
import os
import sys
import time

R = 21888242871839275222246405745257275088548364400416034343698204186575808495617
DELTA = 300
SCALE = 4096
CLAMP = 64
MULT = 128

# Tick of each of the 17 segments before createRound; segment j covers
# [T - (17 - j) * DELTA, T - (16 - j) * DELTA). Adjacent differences stay within +-32 ticks so
# x = x_int / 4096 lies in [-1, 1], the range the circuit's lookup table was calibrated on.
BASE_TICK = 196000
DIFFS = [3, -5, 12, -20, 0, 7, -1, 31, -32, 4, -9, 15, -2, 6, -11, 1]
SEGMENT_TICKS = [BASE_TICK]
for d in DIFFS:
    SEGMENT_TICKS.append(SEGMENT_TICKS[-1] + d)

HERE = os.path.dirname(os.path.abspath(__file__))
FIXED = os.path.join(HERE, "out", "fixed")
OUT = os.path.join(HERE, "out", "fixture")
SRS = os.path.join(HERE, "out", "kzg15.srs")
DEST = os.path.join(HERE, "..", "..", "contracts", "test", "fixtures", "spike_model_proof.json")
def F(n):
    return os.path.join(FIXED, n)


def out_path(n):
    return os.path.join(OUT, n)


def run(r):
    return asyncio.run(_await(r)) if inspect.isawaitable(r) else r


async def _await(r):
    return await r if inspect.isawaitable(r) else r


def floor_div(a, b):
    return a // b  # Python floors toward -inf, matching the contract


def tick_cumulatives(segment_ticks, delta):
    c = [0]
    for t in segment_ticks:
        c.append(c[-1] + t * delta)
    return c


def features(segment_ticks, delta=DELTA):
    c = tick_cumulatives(segment_ticks, delta)
    means = [floor_div(c[j + 1] - c[j], delta) for j in range(len(c) - 1)]
    out = []
    for j in range(len(means) - 1):
        f = max(-CLAMP, min(CLAMP, means[j + 1] - means[j]))
        out.append(f * MULT)
    return out


def encode(x):
    return x if x >= 0 else R - (-x)


def le_hex_to_int(h):
    return int.from_bytes(bytes.fromhex(h), "little")


def expected_inputs():
    feats = features(SEGMENT_TICKS)
    assert len(feats) == 16
    assert all(abs(x) <= SCALE for x in feats), "features must stay in [-1, 1]"
    assert any(x > 0 for x in feats) and any(x < 0 for x in feats)
    return feats


def step_input():
    os.makedirs(OUT, exist_ok=True)
    feats = expected_inputs()
    json.dump({"input_data": [[x / SCALE for x in feats]]}, open(out_path("input.json"), "w"))
    print("features:", feats)


def step_witness():
    run(ezkl().gen_witness(out_path("input.json"), F("model.compiled"), out_path("witness.json"), F("vk.key"), SRS))
    w = json.load(open(out_path("witness.json")))
    got = [le_hex_to_int(h) for h in w["inputs"][0]]
    want = [encode(x) for x in expected_inputs()]
    if got != want:
        raise SystemExit(f"witness inputs differ from contract encoding:\n got {got}\nwant {want}")
    print("witness inputs match contract encoding; outputs:", [le_hex_to_int(h) for h in w["outputs"][0]])


def step_prove():
    print(run(ezkl().prove(out_path("witness.json"), F("model.compiled"), F("pk.key"), out_path("proof.json"), SRS)) is not None)


def step_verify():
    ok = run(ezkl().verify(out_path("proof.json"), F("settings.json"), F("vk.key"), SRS))
    if not ok:
        raise SystemExit("verify failed")
    print("verify:", ok)


def step_export():
    p = json.load(open(out_path("proof.json")))
    inst = [le_hex_to_int(h) for h in p["instances"][0]]
    feats = expected_inputs()
    if len(inst) != 21 or inst[:16] != [encode(x) for x in feats]:
        raise SystemExit("proof instances do not match contract-encoded features")
    outputs = inst[16:]
    if not all(o < R // 2 for o in outputs) or sum(outputs) == 0:
        raise SystemExit(f"bad outputs {outputs}")
    fixture = {
        "description": "Real EZKL proof (spikes/ezkl/out/fixed circuit) over VolMarket features; generated by spikes/ezkl/prove_fixture.py",
        "delta": DELTA,
        "segmentTicks": SEGMENT_TICKS,
        "segmentLayout": "segment j has constant tick segmentTicks[j] over [T-(17-j)*delta, T-(16-j)*delta), T = createRound time",
        "features": feats,
        "outputs": outputs,
        "instances": ["0x%064x" % v for v in inst],
        "proof": p["hex_proof"],
    }
    json.dump(fixture, open(DEST, "w"), indent=2)
    open(DEST, "a").write("\n")
    print("wrote", os.path.normpath(DEST), "outputs", outputs, "proof bytes", (len(p["hex_proof"]) - 2) // 2)


def ezkl():
    import ezkl as e

    return e


STEPS = {"input": step_input, "witness": step_witness, "prove": step_prove, "verify": step_verify, "export": step_export}

if __name__ == "__main__":
    s = sys.argv[1] if len(sys.argv) > 1 else "all"
    for name in STEPS if s == "all" else [s]:
        t0 = time.time()
        STEPS[name]()
        print(f"[{name}] {time.time() - t0:.2f}s")
