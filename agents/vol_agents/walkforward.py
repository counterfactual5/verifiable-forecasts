"""Walk-forward stability evaluation: offline only, the deployed models are not replaced.

Each fold has a cut C. Its bounds come from analysis' vol_params.json written with `--until C`
(read as a file; agents/ never imports analysis/), the three model structures are retrained on the
rounds whose whole read span lies before C, and every forecast is scored on the rounds read within
[C, C + TEST_S). Rounds straddling a cut are dropped (dataset.split_by_time). Labels use the fold's
own bounds, never cm.BOUNDS, so train.labels / lag_buckets are not used here.

Usage: uv run python -m vol_agents.walkforward [--grid PATH] [--folds DIR] [--steps N]
Reads <folds>/<cut>/vol_params.json for every cut in CUTS, writes models/walkforward.json and the
generated block of MODEL_CARD.md between CARD_BEGIN and CARD_END.
"""

import argparse
import json
from pathlib import Path

import numpy as np

from . import contract_math as cm
from . import dataset as ds
from . import train as tr

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "models" / "walkforward.json"
CARD = ROOT / "MODEL_CARD.md"
DEFAULT_FOLDS = ROOT.parent / "analysis" / "data" / "folds"
WEEK_S = 7 * 86400
CUTS = (1790208000, 1790812800, 1791417600, 1792022400)  # 2026-09-24 .. 10-15 00:00 UTC
CARD_BEGIN = "<!-- walkforward:begin (generated by vol_agents.walkforward) -->"
CARD_END = "<!-- walkforward:end -->"
BASELINES = ("uniform", "train_prior", "train_lag_transition")


def load_params(path, cut):
    """The fold's bounds, refused unless they were calibrated on the swaps before `cut`."""
    params = json.loads(Path(path).read_text())
    if params.get("until") != cut:
        raise ValueError(f"{path}: calibrated --until {params.get('until')}, fold cut is {cut}")
    bounds = tuple(int(b) for b in params["bounds"])
    if len(bounds) != cm.BUCKETS - 1 or any(a >= b for a, b in zip(bounds, bounds[1:],
                                                                      strict=False)):
        raise ValueError(f"{path}: bounds {bounds} are not {cm.BUCKETS - 1} increasing values")
    return bounds, params


def bucket(bounds, rv):
    return np.searchsorted(np.array(bounds), rv, side="right")


def fold_split(samples, cut, test_s=WEEK_S):
    trn, test, _ = ds.split_by_time(samples.t_open, [cut, cut + test_s])
    return samples.take(trn), samples.take(test)


def evaluate_fold(samples, cut, bounds, steps, test_s=WEEK_S):
    trn, test = fold_split(samples, cut, test_s)
    if len(trn) == 0 or len(test) == 0:
        raise ValueError(f"fold {tr.utc(cut)}: {len(trn)} training and {len(test)} test rounds")
    y_tr, y_te = bucket(bounds, trn.rv), bucket(bounds, test.rv)
    base = tr.Baselines(y_tr, bucket(bounds, trn.lag_rv))
    forecasts = {"uniform": np.full((len(test), cm.BUCKETS), 1 / cm.BUCKETS),
                 **{f"train_{k}": v for k, v in base.predict(bucket(bounds, test.lag_rv)).items()}}
    models = {}
    for i, spec in enumerate(tr.SPECS):
        p = tr.train(spec, tr.inputs(trn), y_tr, steps, tr.SEED_MODEL + i)
        models[spec.name] = tr.scores(tr.softmax(tr.forward(spec, p, tr.inputs(test))[0]), y_te)
    return {"cut": tr.utc(cut), "test_end": tr.utc(cut + test_s), "bounds": list(bounds),
            "train": tr.span(trn), "test": tr.span(test),
            "bucket_share": {"train": tr.shares(y_tr), "test": tr.shares(y_te)},
            "baselines": {k: tr.scores(v, y_te) for k, v in forecasts.items()},
            "models": models}


def summary(folds):
    names = [s.name for s in tr.SPECS] + list(BASELINES)

    def score(f, name):
        return (f["models"].get(name) or f["baselines"][name])["log_score"]

    return {name: round(float(np.mean([score(f, name) for f in folds])), 4) for name in names}


def render(report):
    """MODEL_CARD block: the mean test-week log score of every fold, from walkforward.json."""
    names = [s.name for s in tr.SPECS] + list(BASELINES)
    head = ["折（测试周起点）", "训练轮数", "测试轮数", "边界 tick²"] + names
    rows = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for f in report["folds"]:
        cells = [f["cut"][:10], str(f["train"]["rounds"]), str(f["test"]["rounds"]),
                 str(f["bounds"])]
        cells += [f"{(f['models'].get(n) or f['baselines'][n])['log_score']:.4f}" for n in names]
        rows.append("| " + " | ".join(cells) + " |")
    mean = report["mean_log_score"]
    rows.append("| " + " | ".join(["平均", "", "", ""] + [f"{mean[n]:.4f}" for n in names]) + " |")
    return "\n".join(rows)


def write_card(card, block):
    text = Path(card).read_text()
    start, end = text.index(CARD_BEGIN) + len(CARD_BEGIN), text.index(CARD_END)
    Path(card).write_text(text[:start] + "\n" + block + "\n" + text[end:])


def card_block(card):
    text = Path(card).read_text()
    return text[text.index(CARD_BEGIN) + len(CARD_BEGIN):text.index(CARD_END)].strip("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", default=str(tr.DEFAULT_GRID))
    ap.add_argument("--folds", default=str(DEFAULT_FOLDS),
                    help="directory of <cut>/vol_params.json from vol_calibrate.py --until <cut>")
    ap.add_argument("--steps", type=int, default=3000)
    a = ap.parse_args()
    samples = ds.build_samples(ds.load_grid(a.grid), stride=tr.STRIDE_S)
    folds = []
    for cut in CUTS:
        bounds, params = load_params(Path(a.folds) / str(cut) / "vol_params.json", cut)
        fold = evaluate_fold(samples, cut, bounds, a.steps)
        fold["bounds_source"] = {k: params.get(k) for k in ("method", "windows", "swapCount",
                                                              "until")}
        folds.append(fold)
        print(json.dumps({k: fold[k] for k in ("cut", "bounds", "models")}))
    report = {"grid": Path(a.grid).name, "steps": a.steps, "stride_s": tr.STRIDE_S,
              "lead_s": ds.LEAD_S, "synthetic_augmentation": False, "folds": folds,
              "mean_log_score": summary(folds)}
    OUT.write_text(json.dumps(report, indent=2) + "\n")
    write_card(CARD, render(report))
    print(render(report))


if __name__ == "__main__":
    main()
