"""Walk-forward stability evaluation: offline only, the deployed models are not replaced.

Each fold has a cut C. The three model structures are retrained on the rounds whose whole read span
lies before C, and every forecast is scored by the mean pinball loss of y = ln(max(RV, 1)) on the
rounds read within [C, C + TEST_S). Rounds straddling a cut are dropped (dataset.split_by_time).
The fold's climatological baseline is the nearest-rank quantiles of its own training rounds' y on
the 2^-12 output grid (the deployed baseline, models/baseline_quantiles.json, uses analysis' swap
windows instead); the lag baseline is the previous hour's y plus training residual quantiles.

Usage: uv run python -m vol_agents.walkforward [--grid PATH] [--steps N]
Writes models/walkforward.json and the generated block of MODEL_CARD.md between CARD_BEGIN and
CARD_END.
"""

import argparse
import json
from pathlib import Path

import numpy as np

from . import contract_math as cm
from . import dataset as ds
from . import train as tr

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "models" / "walkforward.json"
CARD = ROOT / "MODEL_CARD.md"
WEEK_S = 7 * 86400
CUTS = (1790208000, 1790812800, 1791417600, 1792022400)  # 2026-09-24 .. 10-15 00:00 UTC
CARD_BEGIN = "<!-- walkforward:begin (generated by vol_agents.walkforward) -->"
CARD_END = "<!-- walkforward:end -->"
BASELINES = ("climatological", "train_lag_residual")


def fold_split(samples, cut, test_s=WEEK_S):
    trn, test, _ = ds.split_by_time(samples.t_open, [cut, cut + test_s])
    return samples.take(trn), samples.take(test)


def climatological(y):
    """Nearest-rank quantiles of y at the levels, quantized like createRound's baseline."""
    q = np.quantile(y, tr.LEVELS, method="inverted_cdf")
    return np.array(cm.quantize_quantiles(q)) / 2**cm.OUTPUT_SCALE_BITS


def evaluate_fold(samples, cut, steps, test_s=WEEK_S):
    trn, test = fold_split(samples, cut, test_s)
    if len(trn) == 0 or len(test) == 0:
        raise ValueError(f"fold {tr.utc(cut)}: {len(trn)} training and {len(test)} test rounds")
    y_tr, y_te = tr.targets(trn), tr.targets(test)
    base_q = climatological(y_tr)
    models = {}
    for i, spec in enumerate(tr.SPECS):
        p = tr.train(spec, tr.inputs(trn), y_tr, steps, tr.SEED_MODEL + i)
        models[spec.name] = tr.scores(tr.forward(spec, p, tr.inputs(test))[0], y_te)
    return {"cut": tr.utc(cut), "test_end": tr.utc(cut + test_s),
            "baseline_quantiles": base_q.tolist(),
            "train": tr.span(trn), "test": tr.span(test),
            "baselines": {k: tr.scores(v, y_te)
                          for k, v in tr.baseline_forecasts(trn, test, base_q).items()},
            "models": models}


def summary(folds):
    names = [s.name for s in tr.SPECS] + list(BASELINES)

    def score(f, name):
        return (f["models"].get(name) or f["baselines"][name])["mean_pinball"]

    return {name: round(float(np.mean([score(f, name) for f in folds])), 5) for name in names}


def render(report):
    """MODEL_CARD block: the test-week mean pinball loss of every fold, from walkforward.json."""
    names = [s.name for s in tr.SPECS] + list(BASELINES)
    head = ["折（测试周起点）", "训练轮数", "测试轮数"] + names
    rows = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for f in report["folds"]:
        cells = [f["cut"][:10], str(f["train"]["rounds"]), str(f["test"]["rounds"])]
        cells += [f"{(f['models'].get(n) or f['baselines'][n])['mean_pinball']:.4f}"
                  for n in names]
        rows.append("| " + " | ".join(cells) + " |")
    mean = report["mean_pinball"]
    rows.append("| " + " | ".join(["平均", "", ""] + [f"{mean[n]:.4f}" for n in names]) + " |")
    return "\n".join(rows)


def write_card(card, block):
    text = Path(card).read_text()
    start, end = text.index(CARD_BEGIN) + len(CARD_BEGIN), text.index(CARD_END)
    Path(card).write_text(text[:start] + "\n" + block + "\n" + text[end:])


def card_block(card):
    text = Path(card).read_text()
    return text[text.index(CARD_BEGIN) + len(CARD_BEGIN):text.index(CARD_END)].strip("\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--grid", default=str(tr.DEFAULT_GRID))
    ap.add_argument("--steps", type=int, default=3000)
    a = ap.parse_args()
    samples = ds.build_samples(ds.load_grid(a.grid), stride=tr.STRIDE_S)
    folds = []
    for cut in CUTS:
        fold = evaluate_fold(samples, cut, a.steps)
        folds.append(fold)
        print(json.dumps({k: fold[k] for k in ("cut", "models")}))
    report = {"grid": Path(a.grid).name, "steps": a.steps, "stride_s": tr.STRIDE_S,
              "lead_s": ds.LEAD_S, "folds": folds, "mean_pinball": summary(folds)}
    OUT.write_text(json.dumps(report, indent=2) + "\n")
    write_card(CARD, render(report))
    print(render(report))


if __name__ == "__main__":
    main()
